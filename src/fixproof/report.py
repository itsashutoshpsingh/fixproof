"""Tables (results/tables.md, results/*.csv) and results/summary.json from cells.csv/restart.csv."""

from __future__ import annotations

import csv
import json
import math
from collections import Counter, defaultdict

from . import lab

REPO = lab.REPO
RES = REPO / "results"
SCANNERS = ["trivy", "osv-scanner"]          # the CVE scanners that ran
BASELINES = ["ssh-banner"]                   # remote version check from the SSH banner (mine, labelled)
OWN = ["fixproof-verify"]
STATES = ["S0", "S1", "S2", "S3", "S5", "S6", "S7", "S8", "S9"]
STATE_NAMES = {
    "S0": "vulnerable", "S1": "fixed, upstream version", "S2": "fixed by backport",
    "S3": "updated, not restarted", "S5": "config mitigation", "S6": "old kernel on disk, fixed kernel running",
    "S7": "package removed, config left", "S8": "package removed, process still running",
    "S9": "patched, vendored old copy in use",
}
LABEL = {"trivy": "Trivy 0.76.2", "osv-scanner": "OSV-Scanner 2.7.1", "ssh-banner": "SSH banner check (baseline)",
         "fixproof-verify": "fixproof verify (this repo)"}


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def pct(k: int, n: int) -> str:
    return f"{100 * k / n:.1f}%" if n else "n/a"


def ci(k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"{100 * lo:.0f} to {100 * hi:.0f}%" if n else ""


def load():
    cells = list(csv.DictReader(open(RES / "cells.csv")))
    restart = list(csv.DictReader(open(RES / "restart.csv")))
    for r in cells:
        r["repeat"] = int(r["repeat"])
        r["stale_only"] = int(r["stale_only"])
        r["stale_reachable"] = int(r["stale_reachable"])
    return cells, restart


def md_table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    cells, restart = load()
    runs = {(r["distro"], r["host_state"], r["repeat"]) for r in cells}
    unique_cells = {(r["distro"], r["state"], r["cve"]) for r in cells}
    cves = sorted({r["cve"] for r in cells})
    distros = sorted({r["distro"] for r in cells})
    repeats = sorted({r["repeat"] for r in cells})
    sc_rows = [r for r in cells if r["scanner"] in SCANNERS]
    out: list[str] = ["# fixproof results", "",
                      f"{len(runs)} host builds ({len(runs) // max(1, len(repeats))} host states x {len(repeats)} repeats), "
                      f"{len(cves)} CVEs, {len(distros)} distro images, {len(unique_cells)} CVE x distro x state cells, "
                      f"{len(cells)} verdicts. Generated by `fixproof report` from results/cells.csv.", ""]

    # ---- headline: stale vulnerable code running, package already fixed
    stale = [r for r in sc_rows if r["truth"] == "vulnerable" and r["stale_only"] and r["verdict"] != "no_check"]
    stale_fixed = [r for r in stale if r["verdict"] == "fixed"]
    s3 = [r for r in stale if r["state"] == "S3"]
    s3_fixed = [r for r in s3 if r["verdict"] == "fixed"]
    s3_cells = {(r["distro"], r["cve"]) for r in s3}
    s3_cells_all_fixed = {k for k in s3_cells if all(r["verdict"] == "fixed" for r in s3 if (r["distro"], r["cve"]) == k)}
    reach = [r for r in stale if r["stale_reachable"]]
    reach_fixed = [r for r in reach if r["verdict"] == "fixed"]
    per_scanner_s3 = {s: (sum(1 for r in s3_fixed if r["scanner"] == s), sum(1 for r in s3 if r["scanner"] == s))
                      for s in SCANNERS}
    scanners_always_fixed = [s for s, (k, n) in per_scanner_s3.items() if n and k == n]

    # ---- main table: per scanner, per state
    rows = []
    for st in STATES:
        row = [st, STATE_NAMES[st]]
        tv = [r for r in cells if r["state"] == st]
        if not tv:
            continue
        truth_c = Counter(r["truth"] for r in tv if r["scanner"] == "trivy")
        row.append(f"{truth_c['vulnerable']} / {truth_c['fixed']} / {truth_c['mitigated']}")
        for s in SCANNERS + BASELINES + OWN:
            rr = [r for r in tv if r["scanner"] == s]
            if not rr:
                row.append("not run")
                continue
            oc = Counter(r["outcome"] for r in rr)
            ok = oc["correct"] + oc["credited_mitigation"]
            row.append(f"{ok}/{len(rr)} ({pct(ok, len(rr))})")
        rows.append(row)
    out += ["## Correct verdicts by state", "",
            "Truth column: vulnerable / fixed / mitigated verdict slots per scanner (all repeats). Each cell: "
            "correct verdicts / verdicts. For mitigated hosts, \"correct\" means the scanner credited the "
            "mitigation; none did (they report by version).", "",
            md_table(["State", "Meaning", "Truth v/f/m", *[LABEL[s] for s in SCANNERS + BASELINES + OWN]], rows), ""]

    # ---- false fixed by state
    rows = []
    for st in STATES:
        row = [st]
        any_ = False
        for s in SCANNERS + BASELINES:
            rr = [r for r in cells if r["state"] == st and r["scanner"] == s and r["truth"] == "vulnerable"
                  and r["verdict"] != "no_check"]
            k = sum(1 for r in rr if r["verdict"] == "fixed")
            row.append(f"{k}/{len(rr)} ({pct(k, len(rr))}; CI {ci(k, len(rr))})" if rr else "")
            any_ |= bool(rr)
        if any_:
            rows.append(row)
    out += ["## False fixed rate by state", "",
            "Share of verdicts that said \"not vulnerable\" where the truth was vulnerable (scanner has a check for "
            "the CVE on that distro; 95% Wilson interval over all repeats).", "",
            md_table(["State", *[LABEL[s] for s in SCANNERS + BASELINES]], rows), ""]

    # ---- confusion matrices
    for s in SCANNERS + BASELINES + OWN:
        rr = [r for r in cells if r["scanner"] == s]
        if not rr:
            continue
        c = Counter((r["truth"], r["verdict"]) for r in rr)
        rows = [[t, c[(t, "vulnerable")], c[(t, "fixed")], c[(t, "no_check")], c[(t, "error")]]
                for t in ("vulnerable", "fixed", "mitigated")]
        out += [f"### Confusion: {LABEL[s]}", "",
                md_table(["Truth \\ verdict", "vulnerable", "not vulnerable", "no check", "error"], rows), ""]

    # ---- strict vs reachable
    out += ["## Stale code: strict rule against reachable path", "",
            f"Verdicts on cells where the installed package is fixed but a running process maps vulnerable code: "
            f"{len(stale)}. Said fixed: {len(stale_fixed)} ({pct(len(stale_fixed), len(stale))}). Of these, "
            f"{len(reach)} are cells where the stale process is the one that would run the vulnerable path for new "
            f"input (TLS workers, vendored library, sshd where the probe showed it); "
            f"said fixed: {len(reach_fixed)} ({pct(len(reach_fixed), len(reach))}).",
            ""]
    rows = []
    for st in ("S3", "S8", "S9"):
        for reachable in (1, 0):
            rr = [r for r in stale if r["state"] == st and r["stale_reachable"] == reachable]
            if rr:
                k = sum(1 for r in rr if r["verdict"] == "fixed")
                rows.append([st, "yes" if reachable else "no", len(rr), k, pct(k, len(rr))])
    out += [md_table(["State", "Stale path reachable", "Verdicts", "Said fixed", "Rate"], rows), ""]

    # ---- per-CVE S3 table
    rows = []
    for d, cve in sorted({(r["distro"], r["cve"]) for r in cells if r["state"] == "S3"}):
        rr = [r for r in cells if r["state"] == "S3" and r["distro"] == d and r["cve"] == cve]
        t = Counter(r["truth"] for r in rr if r["scanner"] == "trivy").most_common(1)[0][0]
        basis = next(r["basis"] for r in rr if r["scanner"] == "trivy")
        vs = []
        for s in SCANNERS + BASELINES:
            v = Counter(r["verdict"] for r in rr if r["scanner"] == s)
            vs.append(", ".join(f"{k} x{n}" for k, n in v.items()) if v else "")
        rows.append([cve, d, t, *vs, basis[:110]])
    out += ["## Every S3 cell (updated, not restarted)", "",
            md_table(["CVE", "Distro", "Truth", *[LABEL[s] for s in SCANNERS + BASELINES], "Evidence"], rows), ""]

    # ---- coverage (no check)
    rows = []
    for d in distros:
        for s in SCANNERS:
            rr = [r for r in cells if r["distro"] == d and r["scanner"] == s and r["state"] == "S0"]
            nc = sorted({r["cve"] for r in rr if r["verdict"] == "no_check"})
            k = sum(1 for r in rr if r["verdict"] == "vulnerable")
            rows.append([d, LABEL[s], f"{k}/{len(rr)}", ", ".join(nc) or "none"])
    out += ["## Coverage on vulnerable hosts (S0)", "", "No check = the scanner did not flag the CVE on any "
            "vulnerable host of that distro, so its silence elsewhere is not counted as a \"fixed\" verdict.", "",
            md_table(["Distro", "Scanner", "Flagged on S0", "CVEs with no check"], rows), ""]

    # ---- false vulnerable
    rows = []
    for st in STATES:
        row, any_ = [st], False
        for s in SCANNERS + BASELINES:
            rr = [r for r in cells if r["state"] == st and r["scanner"] == s and r["truth"] == "fixed"
                  and r["verdict"] != "no_check"]
            k = sum(1 for r in rr if r["verdict"] == "vulnerable")
            row.append(f"{k}/{len(rr)} ({pct(k, len(rr))})" if rr else "")
            any_ |= bool(rr)
        if any_:
            rows.append(row)
    other = [r for r in sc_rows if r["via_other_package"] == "1"]
    out += ["## False vulnerable rate by state", "", md_table(["State", *[LABEL[s] for s in SCANNERS + BASELINES]], rows),
            "", f"Verdicts that flagged a CVE only through a package other than the one carrying the vulnerable code "
            f"(source-package matching): {len(other)}, in states {dict(Counter(r['state'] for r in other))}.", ""]

    # ---- restart detectors
    rows = []
    tools = sorted({r["tool"] for r in restart})
    rs = defaultdict(Counter)
    for r in restart:
        rs[(r["tool"], r["comm"] or "-")][r["result"]] += 1
    for (tool, comm), c in sorted(rs.items()):
        if comm == "-":
            continue
        n = c["flagged"] + c["missed"]
        rows.append([tool, comm, c["flagged"], c["missed"], c["unavailable"], pct(c["flagged"], n)])
    tot = {t: Counter(r["result"] for r in restart if r["tool"] == t and r["comm"]) for t in tools}
    alarms = {t: Counter(r["result"] for r in restart if r["tool"] == t and not r["comm"]) for t in tools}
    out += ["## Restart detectors on processes running stale vulnerable code", "",
            md_table(["Tool", "Process", "Flagged", "Missed", "Unavailable", "Flagged %"], rows), "",
            "Hosts with no stale vulnerable process: " + "; ".join(
                f"{t}: {a['quiet_no_stale']} quiet, {a['alarm_no_stale']} raised a restart flag, "
                f"{a['unavailable']} unavailable" for t, a in alarms.items()), ""]

    # ---- repeat stability
    groups = defaultdict(set)
    tgroups = defaultdict(set)
    for r in cells:
        groups[(r["distro"], r["host_state"], r["cve"], r["scanner"])].add(r["verdict"])
        tgroups[(r["distro"], r["host_state"], r["cve"])].add(r["truth"])
    stable = sum(1 for v in groups.values() if len(v) == 1)
    tstable = sum(1 for v in tgroups.values() if len(v) == 1)
    out += ["## Repeat stability", "", f"Verdict identical in every repeat: {stable}/{len(groups)} "
            f"(cell, scanner) groups. Truth identical in every repeat: {tstable}/{len(tgroups)} cells.", ""]
    (RES / "tables.md").write_text("\n".join(out) + "\n")

    # ---- summary.json
    trivy_s3 = per_scanner_s3["trivy"]
    osv_s3 = per_scanner_s3["osv-scanner"]
    rt = {t: (tot[t]["flagged"], tot[t]["flagged"] + tot[t]["missed"]) for t in tools}
    nr = rt.get("needrestart", (0, 0))
    vu = rt.get("vuls (checkrestart / needs-restarting)", (0, 0))
    s2 = [r for r in cells if r["state"] == "S2" and r["truth"] == "fixed"]
    banner_s2 = [r for r in s2 if r["scanner"] == "ssh-banner"]
    banner_s2_fv = sum(1 for r in banner_s2 if r["verdict"] == "vulnerable")
    sc_s2 = [r for r in s2 if r["scanner"] in SCANNERS and r["verdict"] != "no_check"]
    sc_s2_fv = sum(1 for r in sc_s2 if r["verdict"] == "vulnerable")
    s5 = [r for r in sc_rows if r["state"] == "S5" and r["truth"] == "mitigated"]
    s5_flag = sum(1 for r in s5 if r["verdict"] == "vulnerable")
    nochk = sorted({(r["distro"], r["cve"]) for r in sc_rows if r["verdict"] == "no_check"})
    headline = (f"On hosts updated but not restarted, {len(s3_fixed)} of {len(s3)} scanner verdicts "
                f"({pct(len(s3_fixed), len(s3))}) said fixed while the old vulnerable code was still running; "
                f"{len(scanners_always_fixed)} of {len(SCANNERS)} scanners did so every time.")
    summary = {
        "project": "fixproof",
        "headline": headline,
        "metrics": [
            {"label": "False fixed, updated not restarted", "value": pct(len(s3_fixed), len(s3))},
            {"label": "Scanners fooled every time", "value": f"{len(scanners_always_fixed)} of {len(SCANNERS)}"},
            {"label": "Stale code verdicts said fixed", "value": f"{len(stale_fixed)} of {len(stale)}"},
            {"label": "Needrestart caught stale programs", "value": pct(*nr)},
            {"label": "Vuls caught stale programs", "value": pct(*vu)},
            {"label": "Backport false vulnerable, scanners", "value": pct(sc_s2_fv, len(sc_s2))},
            {"label": "Backport false vulnerable, banner check", "value": pct(banner_s2_fv, len(banner_s2))},
            {"label": "Mitigated hosts flagged by version", "value": pct(s5_flag, len(s5))},
            {"label": "Host builds", "value": str(len(runs))},
            {"label": "Verdicts scored", "value": str(len(cells))},
        ],
        "charts": [
            {"path": "docs/img/hero_false_fixed.png", "label": "False fixed by state",
             "alt": "Bar chart of the share of vulnerable verdicts each scanner reported as fixed, by host state"},
            {"path": "docs/img/cell_grid.png", "label": "Every cell",
             "alt": "Grid of CVE by distro by state showing truth and each scanner's verdict"},
            {"path": "docs/img/confusion.png", "label": "Confusion matrices",
             "alt": "Truth against verdict counts for each scanner"},
            {"path": "docs/img/restart_detectors.png", "label": "Restart detectors",
             "alt": "Share of processes running stale vulnerable code that needrestart and Vuls flagged"},
            {"path": "docs/img/backport_banner.png", "label": "Backports and banners",
             "alt": "False vulnerable rate on backported hosts for package scanners and a banner version check"},
            {"path": "docs/img/coverage.png", "label": "Coverage by distro",
             "alt": "Share of vulnerable S0 cells each scanner flagged, per distro"},
            {"path": "docs/img/pipeline.png", "label": "Pipeline",
             "alt": "Diagram of the lab: host states, evidence collector, scanners, scoring"},
        ],
        "viz": [
            {"title": "Updated but not restarted: share of verdicts that said fixed while old code ran", "unit": "%",
             "bars": [{"label": LABEL[s].rsplit(" ", 1)[0], "value": round(100 * k / n, 1) if n else 0, "tone": "bad"}
                      for s, (k, n) in per_scanner_s3.items()]},
            {"title": "Restart detectors: share of stale vulnerable programs they flagged", "unit": "%",
             "bars": [{"label": "Needrestart", "value": round(100 * nr[0] / nr[1], 1) if nr[1] else 0, "tone": "good"},
                      {"label": "Vuls scan", "value": round(100 * vu[0] / vu[1], 1) if vu[1] else 0, "tone": "warn"}]},
            {"title": "Backported fixes: version-string checks cry wolf", "unit": "%",
             "bars": [{"label": "Package scanners", "value": round(100 * sc_s2_fv / len(sc_s2), 1) if sc_s2 else 0,
                       "tone": "good"},
                      {"label": "SSH banner check", "value": round(100 * banner_s2_fv / len(banner_s2), 1)
                       if banner_s2 else 0, "tone": "bad"}]},
        ],
    }
    detail = {"s3_trivy": trivy_s3, "s3_osv": osv_s3, "s3_unique_cells": len(s3_cells),
              "s3_unique_cells_all_said_fixed": len(s3_cells_all_fixed), "reachable": [len(reach_fixed), len(reach)],
              "stale": [len(stale_fixed), len(stale)], "no_check": [list(x) for x in nochk],
              "restart": {t: list(v) for t, v in rt.items()}, "repeat_stable": [stable, len(groups)],
              "truth_stable": [tstable, len(tgroups)], "backport_scanners": [sc_s2_fv, len(sc_s2)],
              "backport_banner": [banner_s2_fv, len(banner_s2)], "s5_flagged": [s5_flag, len(s5)],
              "host_builds": len(runs), "verdicts": len(cells), "cells": len(unique_cells)}
    (RES / "headline_numbers.json").write_text(json.dumps(detail, indent=1) + "\n")
    (RES / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(headline)
